// effort — главный рычаг скорости. Умолчания подобраны замером; перебивается EFFORT= в .env.
const EFFORT = process.env.EFFORT || null;
const STEPS = {
  read: { schema: READ_SCHEMA, instructions: STEP_READ, max: 12000, effort: "medium" },
  refine: { schema: REFINE_SCHEMA, instructions: STEP_REFINE, max: 20000, effort: "medium" },
  decide_paradox: { schema: DECIDE_PARADOX, instructions: STEP_PARADOX, max: 16000, effort: "medium" },
  decide_problem: { schema: DECIDE_PROBLEM, instructions: STEP_PROBLEM, max: 8000, effort: "low" },
  decide_dilemma: { schema: DECIDE_DILEMMA, instructions: STEP_DILEMMA, max: 8000, effort: "low" },
};

/* ------------------------------- запуск ------------------------------ */

function userTurn(step, ctx, instructions) {
  const p = [instructions];
  p.push(`СИТУАЦИЯ ПОЛЬЗОВАТЕЛЯ (его словами):\n${ctx.situation}`);
  if (ctx.read) p.push(`ТВОЁ ПЕРВИЧНОЕ ЧТЕНИЕ:\n${JSON.stringify(ctx.read, null, 1)}`);
  if (ctx.answers?.length) {
    p.push("ОТВЕТЫ ПОЛЬЗОВАТЕЛЯ НА ТВОИ ВОПРОСЫ:\n" +
      ctx.answers.map(a => `— ${a.question}\n  ${a.answer || "(пропущен)"}`).join("\n"));
  }
  if (ctx.refine) p.push(`ТВОЁ УТОЧНЁННОЕ ОПИСАНИЕ:\n${JSON.stringify(ctx.refine, null, 1)}`);
  if (ctx.chosenType) {
    const ru = { problem: "проблема", dilemma: "дилемма", paradox: "парадокс" }[ctx.chosenType];
    p.push(`ПОЛЬЗОВАТЕЛЬ НАЗВАЛ СВОЙ ВЫЗОВ: ${ru}. Это его решение, работай в этой рамке.`);
  }
  if (ctx.chosenAxis) p.push(`ВЫБРАННАЯ ОСЬ: ${ctx.chosenAxis.a} — ${ctx.chosenAxis.b}`);
  if (ctx.focus) {
    p.push(`ПОЛЬЗОВАТЕЛЬ ВЫБРАЛ РАЗБИРАТЬ ИМЕННО ЭТОТ ВЫЗОВ ИЗ СИТУАЦИИ: «${ctx.focus}».
Сделай его основным (primary), остальные оставь в списке. Вопросы задавай про него.`);
  }
  if (ctx.extra) p.push(`ЧЕЛОВЕК ДОРАССКАЗАЛ:\n${ctx.extra}`);
  return p.join("\n\n");
}

/**
 * Выполняет один шаг агента. onThinking получает краткое резюме рассуждения по мере генерации.
 * Возвращает разобранный JSON по схеме шага.
 */
export async function runStep(step, ctx, onThinking = () => {}, providerId = null) {
  const cfg = STEPS[step];
  if (!cfg) throw new Error(`Неизвестный шаг: ${step}`);
  const p = (providerId && getProvider(providerId)) || provider;
  if (!p) throw new Error("NO_KEY");

  const { json, usage } = await p.run({
    system: SYSTEM,
    user: userTurn(step, ctx, cfg.instructions),
    schema: cfg.schema,
    maxTokens: cfg.max,
    effort: EFFORT || cfg.effort,
    onThinking,
  });
  return { data: json, usage, provider: { id: p.id, label: p.label, model: p.model } };
}
