function renderTypes() {
  return TYPES.map(t =>
    `### ${t.name} — способ: ${t.verb}\n` +
    `Этимология: ${t.core}\n${t.def}\n` +
    `Признаки:\n${t.signs.map(s => "- " + s).join("\n")}\n` +
    `Уместные инструменты: ${t.tools}\n` +
    `Время: ${t.time}. После действия: ${t.after}. Цена ошибки: ${t.cost}.`
  ).join("\n\n");
}

function renderCriteria() {
  return CRITERIA.map(c =>
    `### ${c.name}${c.necessary ? " (НЕОБХОДИМЫЙ)" : ""}${c.signal ? " (сигнальный, не определяющий)" : ""} — про ${c.about}\n` +
    c.text + (c.examples.length ? "\nПримеры: " + c.examples.join(" · ") : "")
  ).join("\n\n");
}

function renderMisdiagnosis() {
  const label = { problem: "проблема", dilemma: "дилемма", paradox: "парадокс" };
  return Object.entries(MISDIAGNOSIS).map(([real, wrong]) =>
    Object.entries(wrong).map(([w, m]) =>
      `Это ${label[real]}, а приняли за ${label[w]} → «${m.h}». ${m.t} ${m.c}`
    ).join("\n")
  ).join("\n");
}

function renderPassports() {
  return PASSPORTS.map(p =>
    `### ${p.name} [id: ${p.id}]\n` +
    `Тип по Smith & Lewis: ${p.sl}. Конститутивность — вердикт: ${p.verdict}.\n` +
    `Полюс A — ${p.a.n}: ${p.a.is}\n  даёт: ${p.a.gives}\n  патология перекоса: ${p.a.over}\n` +
    `Полюс B — ${p.b.n}: ${p.b.is}\n  даёт: ${p.b.gives}\n  патология перекоса: ${p.b.over}\n` +
    `Уровень проявления: ${p.level}\nТемпоральное поведение: ${p.temporal}\n` +
    `Триггер активации: ${p.trigger}\nСпособ работы: ${p.way}\nТипичная ошибка диагноза: ${p.mistake}`
  ).join("\n\n");
}

